import express from 'express';
import {
  predictCrowdLevel,
  generateHourlyForecast,
  getPeakHours,
  getHistoricalPattern
} from '../services/predictionEngine.js';
import { DEMO_LOCATIONS, findDemoLocation } from '../services/crowdEngine.js';

const router = express.Router();

// POST /api/prediction/forecast
// Body: { locationId, targetTime, hours = 24 }
router.post('/forecast', async (req, res, next) => {
  try {
    const { locationId, locationName, targetTime, hours = 24 } = req.body;

    const loc = findDemoLocation(locationId || locationName) || DEMO_LOCATIONS[0];

    const arrivalTime = targetTime ? new Date(targetTime) : new Date(Date.now() + 2 * 3600 * 1000);
    const targetPrediction = predictCrowdLevel(loc, arrivalTime);
    const hourlyForecast = generateHourlyForecast(loc, 0, Math.min(24, hours));
    const peakInfo = getPeakHours(loc);
    const historicalPattern = getHistoricalPattern(loc, arrivalTime.getDay());

    // Alternative recommendation: find nearby location with lower predicted crowd
    const alternativeLocs = DEMO_LOCATIONS
      .filter(l => l._id !== loc._id && l.category === loc.category)
      .map(l => ({
        ...l,
        predicted: predictCrowdLevel(l, arrivalTime)
      }))
      .sort((a, b) => a.predicted.predictedScore - b.predicted.predictedScore);

    const bestAlternative = alternativeLocs[0] || null;

    res.json({
      success: true,
      location: {
        id: loc._id,
        name: loc.name,
        category: loc.category,
        baselineCrowd: loc.baselineCrowd
      },
      targetTime: arrivalTime.toISOString(),
      prediction: targetPrediction,
      recommendation: bestAlternative && bestAlternative.predicted.predictedScore < targetPrediction.predictedScore - 15
        ? {
            suggestAlternative: true,
            alternativeLocation: bestAlternative.name,
            alternativeScore: bestAlternative.predicted.predictedScore,
            alternativeCategory: bestAlternative.predicted.category,
            savingsPercent: targetPrediction.predictedScore - bestAlternative.predicted.predictedScore,
            message: `Consider visiting ${bestAlternative.name} instead for ${targetPrediction.predictedScore - bestAlternative.predicted.predictedScore}% lower crowd density.`
          }
        : {
            suggestAlternative: false,
            message: `Current timing looks optimal for ${loc.name}.`
          },
      hourlyForecast,
      peakHours: peakInfo,
      historicalPattern,
      disclaimer: 'Predictive crowd forecast generated by FLOWWISE temporal-weighted machine learning simulator.'
    });
  } catch (err) {
    next(err);
  }
});

export default router;
